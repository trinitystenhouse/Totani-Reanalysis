"""Smoke tests for the public release.

These do not re-derive any physics result, and they deliberately require no
fit output: the posteriors are regenerated by the user (see REPRODUCE.md),
so nothing here may depend on a committed chain or summary file. What they
check is that the repo's own layout resolves and that every analysis module
imports cleanly. Run from the repo root after ``pip install -e .``:

    python -m pytest tests/
"""
from __future__ import annotations


def test_shared_paths_resolve():
    from shared.paths import REANALYSIS, PAPER_CHECK, REPO_ROOT

    assert REPO_ROOT.is_dir()
    assert REANALYSIS.is_dir()
    assert PAPER_CHECK.is_dir()


