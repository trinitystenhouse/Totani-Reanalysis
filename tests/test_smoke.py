def test_halo_posterior_root_is_configurable():
    """The pixel-level posterior is not shipped. Downstream code resolves it
    through ``HALO_POSTERIOR_ROOT``; this checks the override is honoured so
    a regenerated posterior can be pointed at from anywhere."""
    import importlib
    import os

    import shared.paths

    os.environ["HALO_POSTERIOR_ROOT"] = "/tmp/some-regenerated-posterior"
    try:
        importlib.reload(shared.paths)
        assert str(shared.paths.PIXELWISE_MCMC) == "/tmp/some-regenerated-posterior"
    finally:
        del os.environ["HALO_POSTERIOR_ROOT"]
        importlib.reload(shared.paths)
